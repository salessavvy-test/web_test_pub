const addThreeNumbers = require('./addThreeNumbers');

// Example usage
const result1 = addThreeNumbers(5, 10, 15);
console.log(`5 + 10 + 15 = ${result1}`); // Output: 30

const result2 = addThreeNumbers(100, 200, 300);
console.log(`100 + 200 + 300 = ${result2}`); // Output: 600

const result3 = addThreeNumbers(1.5, 2.5, 3.0);
console.log(`1.5 + 2.5 + 3.0 = ${result3}`); // Output: 7
